#ifndef _UAPI_LINUX_XPON_H
#define _UAPI_LINUX_XPON_H

#define XPON_GENL_NAME		"xpon"
#define XPON_GENL_VERSION	2

/* An OAM frame includes the Ethernet header, but excludes the FCS. */
#define XPON_OAM_FRAME_MAX	1514

enum xpon_onu_type {
	XPON_ONU_HGU,
	XPON_ONU_SFU,
};

enum xpon_endpoint_type {
	XPON_ENDPOINT_GEM,
	XPON_ENDPOINT_LLID,
};

enum xpon_link_state {
	XPON_LINK_DISABLED,
	XPON_LINK_REGISTERING,
	XPON_LINK_REGISTERED,
};

#define XPON_CAP_ENDPOINTS	(1U << 0)
#define XPON_CAP_OAM		(1U << 1)
#define XPON_CAP_REPORT		(1U << 2)
#define XPON_CAP_LINK_ADMIN	(1U << 3)

/* Each mode is a single bit; capability masks combine these values. */
enum xpon_mode {
	XPON_MODE_GPON = (1U << 1),	/* ITU-T G.984 (2.5Gbps RX / 1.2Gbps TX) */
	XPON_MODE_EPON = (1U << 2),	/* IEEE 802.3ah (1Gbps) */
	XPON_MODE_XEPON = (1U << 3),	/* IEEE 802.3av (10G) */
	XPON_MODE_XGPON = (1U << 4),	/* ITU-T G.987 (10Gbps RX / 2.5Gbps TX) */
	XPON_MODE_XGSPON = (1U << 5),	/* ITU-T G.9807.1 (10Gbps) */
	XPON_MODE_NGPON2 = (1U << 6),	/* ITU-T G.989 (10Gbps per channel) */
	XPON_MODE_25GSPON = (1U << 7),	/* 25GS-PON MSA specification (25Gbps) */
	XPON_MODE_50GPON = (1U << 8),	/* ITU-T G.9804 (50Gbps) */
	XPON_MODE_25GEPON = (1U << 9),	/* IEEE 802.3ca (25Gbps) */
	XPON_MODE_50GEPON = (1U << 10),	/* IEEE 802.3ca (50Gbps) */

	__XPON_MODE_MAX,
};
#define XPON_MODE_MAX (__XPON_MODE_MAX - 1)
#define XPON_MODE_MASK ((XPON_MODE_MAX << 1) - XPON_MODE_GPON)

enum xpon_registration_state {
	XPON_REGISTRATION_DOWN,
	XPON_REGISTRATION_DISCOVERY,
	XPON_REGISTRATION_REGISTERING,
	XPON_REGISTRATION_OPERATIONAL,
};

enum xpon_cmd {
	XPON_CMD_UNSPEC,
	XPON_CMD_GET,
	XPON_CMD_GET_CAPS,
	XPON_CMD_GET_STATE,
	XPON_CMD_SET_MODE,
	XPON_CMD_EVENT,

	XPON_CMD_UNI_GET,
	XPON_CMD_LINK_GET,
	XPON_CMD_LINK_SET,
	XPON_CMD_ENDPOINT_NEW,
	XPON_CMD_ENDPOINT_GET,
	XPON_CMD_ENDPOINT_SET,
	XPON_CMD_ENDPOINT_DEL,
	XPON_CMD_OAM_TX,
	XPON_CMD_OAM_RX,
	XPON_CMD_REPORT_GET,
	XPON_CMD_REPORT_SET,

	__XPON_CMD_MAX,
};
#define XPON_CMD_MAX (__XPON_CMD_MAX - 1)

enum xpon_attr {
	XPON_ATTR_UNSPEC,
	XPON_ATTR_IFINDEX,
	XPON_ATTR_MODE,		/* u32, one enum xpon_mode bit */
	XPON_ATTR_AVAILABLE_MODES, /* u32, enum xpon_mode bitmap */
	XPON_ATTR_REGISTRATION,
	XPON_ATTR_CARRIER,
	XPON_ATTR_SIGNAL_DETECT,
	XPON_ATTR_LOS,
	XPON_ATTR_CHANGED,

	XPON_ATTR_CAPABILITIES,
	XPON_ATTR_MAX_LINKS,
	XPON_ATTR_MAX_ENDPOINTS,
	XPON_ATTR_MAX_QUEUES,
	XPON_ATTR_REPORT_SETS,
	XPON_ATTR_ONU_TYPE,
	XPON_ATTR_UNI_COUNT,
	XPON_ATTR_ID,
	XPON_ATTR_TYPE,
	XPON_ATTR_WIRE_ID,
	XPON_ATTR_SCHEDULER_ID,
	XPON_ATTR_LINK_ID,
	XPON_ATTR_QUEUE,
	XPON_ATTR_ENABLED,
	XPON_ATTR_NETDEV_IFINDEX,
	XPON_ATTR_NAME,
	XPON_ATTR_LINK_STATE,
	XPON_ATTR_RX_PACKETS,
	XPON_ATTR_TX_PACKETS,
	XPON_ATTR_PAD,
	XPON_ATTR_FRAME,
	XPON_ATTR_REPORT_SET,
	XPON_ATTR_THRESHOLD_TQ,
	XPON_ATTR_MAX_REPORT_SETS,

	__XPON_ATTR_MAX,
};
#define XPON_ATTR_MAX (__XPON_ATTR_MAX - 1)

#endif /* _UAPI_LINUX_XPON_H */
